use std::fs;
use std::io::{self, Write};
use std::path::PathBuf;

use anyhow::Context;
use clap::Parser;
use rustc_hash::FxHashMap;

use tptp2rsbdd::download::{fetch, problem_path};
use tptp2rsbdd::tptp::{header, parse};
use tptp2rsbdd::translate::translate;

#[derive(Parser, Debug)]
#[clap(
    author,
    version,
    about,
    long_about = None,
    after_help = "The fof, cnf and tff (TF0 and TF1, without arithmetic) languages are supported.\n\n\
Examples:\n  \
tptp2rsbdd PUZ001-1 | rsbdd - --prove\n  \
tptp2rsbdd SET001-1 set001.txt\n  \
tptp2rsbdd --file problem.p"
)]
struct Args {
    #[clap(value_parser, value_name = "PROBLEM")]
    /// The name of the TPTP problem, such as PUZ001-1, or a path with --file
    problem: String,

    #[clap(value_parser, value_name = "OUTPUT")]
    /// The output rsbdd file [default: stdout]
    output: Option<PathBuf>,

    #[clap(short, long)]
    /// Read the problem from a local file instead of downloading it
    file: bool,

    #[clap(long, value_parser, value_name = "DIR", env = "TPTP")]
    /// A local copy of the TPTP library: problems and includes are read from it if they exist, and downloaded
    /// otherwise
    tptp_dir: Option<PathBuf>,
}

fn main() -> anyhow::Result<()> {
    let version = env!("CARGO_PKG_VERSION");
    let args = Args::parse();

    // a file may be included by several files
    let mut cache: FxHashMap<String, String> = FxHashMap::default();
    let mut read = |path: &str| -> anyhow::Result<String> {
        if let Some(text) = cache.get(path) {
            return Ok(text.clone());
        }
        let text = match args.tptp_dir.as_ref().map(|dir| dir.join(path)) {
            Some(local) if local.is_file() => fs::read_to_string(&local)
                .with_context(|| format!("reading {}", local.display()))?,
            _ => fetch(path)?,
        };
        cache.insert(path.to_string(), text.clone());
        Ok(text)
    };

    let name = &args.problem;
    let text = if args.file {
        fs::read_to_string(name).with_context(|| format!("reading {name}"))?
    } else {
        read(&problem_path(name)?)?
    };

    let formulas = parse(&text, &mut read).with_context(|| format!("parsing {name}"))?;

    let run = args
        .output
        .as_ref()
        .map_or_else(|| "FILE".to_string(), |o| o.display().to_string());
    let header = format!(
        "{}\n\nGenerated by tptp2rsbdd version {version} from {name}\n\nRun with:\n    rsbdd {run} --prove",
        header(&text)
    );

    let output = translate(&formulas, header.trim_start());
    match &args.output {
        Some(path) => {
            fs::write(path, output).with_context(|| format!("writing {}", path.display()))
        }
        None => Ok(io::stdout().write_all(output.as_bytes())?),
    }
}
